"""
Why the census's remaining entries are confined: forced subfields, and chance.

A rule's eigenvalue at a character c is lambda(c) = f(zeta^c). Two facts tie eigenvalues together:

- Frobenius: lambda(2c) = lambda(c)^2.
- Symmetry: if a matrix M (mod m) maps the rule's translations onto themselves, then
  lambda(M^T c) = lambda(c).

So if 2^i c = M^T c for a symmetry M, then lambda(c)^(2^i) = lambda(c): the eigenvalue at c lies in
the subfield F(2^i), whatever the rule's coefficients. Call the least such i the forced degree
of c. The symmetries searched are s A, with A a matrix of entries in {-1, 0, 1} and s a power of
2 mod m; s A with s = 2^g and A = 1 is pilot 4's pure half-Frobenius case.

Every eigenvalue in a forced subfield F(2^i) whose nonzero elements are all cubes in F(2^d) is a
cube by structure. The others are free. Under the null model, each free class of characters (an
orbit of the group the symmetries and Frobenius generate) has a value spread uniformly over the
nonzero elements of its forced field, independently of the others, so it is a cube with
probability gcd(2^i - 1, (2^d - 1)/3) / (2^i - 1).
"""

from __future__ import annotations

import functools
import itertools
import math
import sys
from pathlib import Path

import sympy

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "llm-pilot-37"))

import census  # noqa: E402
from census import eigen  # noqa: E402

UNIT = [A for A in itertools.product((-1, 0, 1), repeat=4) if A[0] * A[3] - A[1] * A[2] in (1, -1)]


def symmetries(f: frozenset, m: int) -> list[tuple[int, int, int, int]]:
    """Every s A (mod m) with s a power of 2 and A in UNIT that maps f onto itself mod m."""
    support = {(x % m, y % m) for x, y in f}
    powers = sorted({pow(2, e, m) for e in range(eigen.field(m)[1])})
    out = set()
    for s in powers:
        for a, b, c, d in UNIT:
            M = ((s * a) % m, (s * b) % m, (s * c) % m, (s * d) % m)
            if {
                ((M[0] * x + M[1] * y) % m, (M[2] * x + M[3] * y) % m) for x, y in support
            } == support:
                out.add(M)
    return sorted(out)


@functools.cache
def partition(m: int, sym: tuple) -> tuple[tuple[tuple[int, int], int, int], ...]:
    """The character classes at odd m for a symmetry set: orbits of the group generated by
    Frobenius and the transposed symmetries, each as (representative, size, forced degree)."""
    d = eigen.field(m)[1]

    def act(M, a, b):
        return (M[0] * a + M[2] * b) % m, (M[1] * a + M[3] * b) % m

    seen, out = set(), []
    for j, k in itertools.product(range(m), repeat=2):
        if (j, k) == (0, 0) or (j, k) in seen:
            continue
        orbit, stack = {(j, k)}, [(j, k)]
        while stack:
            a, b = stack.pop()
            for nxt in [(2 * a % m, 2 * b % m)] + [act(M, a, b) for M in sym]:
                if nxt not in orbit:
                    orbit.add(nxt)
                    stack.append(nxt)
        seen |= orbit
        images, stack = {(j, k)}, [(j, k)]  # the orbit of c under the symmetries alone
        while stack:
            a, b = stack.pop()
            for M in sym:
                nxt = act(M, a, b)
                if nxt not in images:
                    images.add(nxt)
                    stack.append(nxt)
        degree = next(
            i for i in range(1, d + 1) if (pow(2, i, m) * j % m, pow(2, i, m) * k % m) in images
        )
        out.append(((j, k), len(orbit), degree))
    return tuple(out)


def classes(f: frozenset, m: int) -> list[dict]:
    """The character classes of f at odd m, each with its size, forced degree and eigenvalue."""
    zeta = census.setup(m)[3]
    out = []
    for (j, k), size, degree in partition(m, tuple(symmetries(f, m))):
        value = 0
        for x, y in f:
            value ^= zeta[(x * j + y * k) % m]
        out.append({"rep": (j, k), "size": size, "degree": degree, "value": value})
    return out


@functools.cache
def cube_chance(i: int, m: int) -> float:
    """The chance that a uniform nonzero element of F(2^i) is a cube in F(2^d)*."""
    N = 2 ** eigen.field(m)[1] - 1
    return math.gcd(2**i - 1, N // 3) / (2**i - 1)


def analyse(f: frozenset, m: int) -> dict:
    """Forced and free classes, whether the rule is confined by structure, and its chance."""
    mod, d, N, _, _ = census.setup(m)
    cs = classes(f, m)
    nonzero = [c for c in cs if c["value"]]
    free = [c for c in nonzero if cube_chance(c["degree"], m) < 1]
    chance = math.prod(cube_chance(c["degree"], m) for c in nonzero)
    return {
        "classes": len(cs),
        "zero": len(cs) - len(nonzero),
        "free": len(free),
        "free_degrees": sorted(c["degree"] for c in free),
        "forced": not free and bool(nonzero),
        "chance": chance,
        "cubes": all(eigen._pow(c["value"], N // 3, mod, d) == 1 for c in nonzero)
        and bool(nonzero),
    }


def full_symmetries(f: frozenset, m: int) -> list[tuple[int, int, int, int]]:
    """Every matrix in GL2(Z/m) that maps f's translations onto themselves mod m, found through
    the largest prime-power factor P of m: candidates mod P first, then every lift mod m.
    For the small m of the census (it is about m^4 / P^4 * P^4-search work)."""
    support = {(x % m, y % m) for x, y in f}
    P = max(p**e for p, e in sympy.factorint(m).items())
    Q = m // P

    def keeps(M, mod, pts):
        return all(
            ((M[0] * x + M[1] * y) % mod, (M[2] * x + M[3] * y) % mod) in pts for x, y in pts
        )

    def invertible(M, mod):
        return math.gcd((M[0] * M[3] - M[1] * M[2]) % mod, mod) == 1

    small = {(x % P, y % P) for x, y in support}
    mod_p = [
        M for M in itertools.product(range(P), repeat=4) if invertible(M, P) and keeps(M, P, small)
    ]
    mod_q = [M for M in itertools.product(range(Q), repeat=4) if invertible(M, Q)]
    lift = {
        (a, b): next(x for x in range(m) if x % P == a and x % Q == b)
        for a in range(P)
        for b in range(Q)
    }
    out = []
    for Mp in mod_p:
        for Mq in mod_q:
            M = tuple(lift[(a, b)] for a, b in zip(Mp, Mq, strict=True))
            if keeps(M, m, support):
                out.append(M)
    return sorted(out)


def distinct_free(f: frozenset, m: int, sym: tuple) -> tuple[int, int, float]:
    """With a given symmetry set: the free classes, their distinct values up to Frobenius, and
    the chance model's probability that all nonzero values are cubes."""
    mod, d, N, zeta, _ = census.setup(m)
    nonzero = []
    for (j, k), _, degree in partition(m, sym):
        value = 0
        for x, y in f:
            value ^= zeta[(x * j + y * k) % m]
        if value:
            nonzero.append((degree, value))
    free = [v for g, v in nonzero if cube_chance(g, m) < 1]

    def canon(v):
        best = w = v
        for _ in range(d):
            w = eigen._pow(w, 2, mod, d)
            best = min(best, w)
        return best

    chance = math.prod(cube_chance(g, m) for g, _ in nonzero)
    return len(free), len({canon(v) for v in free}), chance
