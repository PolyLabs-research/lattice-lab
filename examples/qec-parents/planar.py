"""
A planar pair's quotient ring: how many independent excitations it has, and its periods.

A planar pair (A, B) is two Laurent polynomials over GF(2) in x and y. Its quotient
M = GF(2)[x, 1/x, y, 1/y] / (A, B) has finite dimension Q unless A and B share a factor. Every
torus code that wraps the pair is 2 dim M/(wrapping relations), so k <= 2 Q, and Q is at most the
mixed area of the two Newton polygons (Bernstein's theorem). x and y act on M invertibly; their
orders are the pair's periods, and k = 2 Q on the l x m torus exactly when x^l = y^m = 1 in M.

Polynomials are lists of exponent pairs with nonnegative entries (parents.key's triangles).
"""

from __future__ import annotations

from sympy import Poly, groebner, symbols

x, y, z = symbols("x y z")
GENS = (x, y, z)


def _expr(P):
    return sum(x**p * y**q for p, q in P)


def _standard(lead) -> list | None:
    """The monomials divisible by no leading monomial, or None when there are infinitely many."""
    if lead == [(0, 0, 0)]:
        return []
    for i in range(3):
        if not any(lm[i] and sum(1 for e in lm if e) == 1 for lm in lead):
            return None
    basis, frontier, seen = [], [(0, 0, 0)], {(0, 0, 0)}
    while frontier:
        mon = frontier.pop()
        if any(all(a >= b for a, b in zip(mon, lm, strict=True)) for lm in lead):
            continue
        basis.append(mon)
        for i in range(3):
            nxt = tuple(e + (j == i) for j, e in enumerate(mon))
            if nxt not in seen:
                seen.add(nxt)
                frontier.append(nxt)
    return sorted(basis)


def quotient(A, B, extra=()):
    """(basis, G): a monomial basis of the quotient and its Groebner basis; basis is None when
    the quotient is infinite. z stands for 1/(x y). `extra` adds relations (sympy expressions)."""
    G = groebner([_expr(A), _expr(B), x * y * z - 1, *extra], *GENS, modulus=2, order="grevlex")
    lead = [Poly(g, *GENS, modulus=2).monoms(order="grevlex")[0] for g in G.exprs]
    return _standard(lead), G


def dimension(A, B, extra=()) -> int | None:
    basis, _ = quotient(A, B, extra)
    return None if basis is None else len(basis)


def k_on_torus(A, B, ell: int, m: int) -> int:
    """k of the pair wrapped on the l x m torus, from the quotient: 2 dim M/(x^l - 1, y^m - 1)."""
    return 2 * dimension(A, B, (x**ell - 1, y**m - 1))


def _times(G, basis, var) -> list[int]:
    """Multiplication by var on the quotient: column i is var * basis[i], a bitmask."""
    index = {b: i for i, b in enumerate(basis)}
    cols = []
    for b in basis:
        rem = Poly(G.reduce(var * x ** b[0] * y ** b[1] * z ** b[2])[1], *GENS, modulus=2)
        cols.append(sum(1 << index[mon] for mon in rem.monoms()))
    return cols


def _order(cols, start: int, cap: int) -> int | None:
    """The least n >= 1 with M^n e = e for the basis vector e = start, or None above cap. The
    quotient is generated by 1, so with e the monomial 1 this is the order of var in the ring."""
    v, n = 1 << start, 0
    while n < cap:
        w, i = 0, 0
        while v:
            if v & 1:
                w ^= cols[i]
            v >>= 1
            i += 1
        v, n = w, n + 1
        if v == 1 << start:
            return n
    return None


def mixed_area(A, B) -> int:
    """The mixed area of the Newton polygons of A and B: area(A + B) - area(A) - area(B)."""

    def twice_area(pts) -> int:
        pts = sorted(set(pts))
        if len(pts) < 3:
            return 0

        def cross(o, a, b):
            return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

        lower, upper = [], []
        for p in pts:
            while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
                lower.pop()
            lower.append(p)
        for p in reversed(pts):
            while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
                upper.pop()
            upper.append(p)
        hull = lower[:-1] + upper[:-1]
        nxt = hull[1:] + hull[:1]
        return abs(sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(hull, nxt, strict=True)))

    total = [(a[0] + b[0], a[1] + b[1]) for a in A for b in B]
    return (twice_area(total) - twice_area(A) - twice_area(B)) // 2


def signature(A, B, cap: int = 1_000_000) -> dict:
    """Q, the mixed area, and the periods of x and y (None above cap, or when Q is infinite or
    0)."""
    basis, G = quotient(A, B)
    out = {"Q": None if basis is None else len(basis), "mixed_area": mixed_area(A, B),
           "period_x": None, "period_y": None}  # fmt: skip
    if basis:
        one = basis.index((0, 0, 0))
        out["period_x"] = _order(_times(G, basis, x), one, cap)
        out["period_y"] = _order(_times(G, basis, y), one, cap)
    return out
