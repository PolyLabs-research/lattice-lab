"""
The open part of the triangular lattices' period law, checked one odd part at a time.

docs/parity-lattices.md proves that on both triangular lattices the n x n torus (n = 2^v m, m odd,
m >= 3) has period 2 * 2^v * L(m), where L(m) is the order of the group generated by the nonzero
eigenvalues lambda(alpha, beta), over pairs of m-th roots of unity, of the rule's square F:

    edge          lambda = 1 + c(alpha) + c(beta) + c(alpha beta)
    edge+vertex   lambda = c(alpha) + c(beta) + c(alpha beta) + c(alpha / beta)
                           + c(alpha beta^2) + c(alpha^2 beta)               (c(z) = z + 1/z)

They lie in F(2^s), s = sord(m), so L(m) divides Q = 2^s - 1, and the law holds at m exactly when
they generate all of F(2^s)^*: when, for every prime r of Q, some eigenvalue is not an r-th power.
The method is examples/xor-periods-proof/check_odd.py's: in GF(2)[z]/(z^m - 1) the element
T = lambda(z^p, z^q) has the eigenvalues on the line (p, q) as its components, and some component is
a nonzero non-r-th power exactly when T^(Q/r) != T^Q.

Lines are tried in this order: one fixed first line, then one line per class of primitive vectors
(p, q) up to scaling by units mod m. Those classes cover every pair (alpha, beta), so a prime left
unresolved after all of them is a counterexample (when the factorisation is complete). The first
lines are where each rule meets a 1D rule: on the line (1, 0) the edge+vertex eigenvalue is
c(alpha)^2 (rule 90), and on (1, 1) the edge eigenvalue is (1 + c(alpha))^2 (rule 150).

The hexagon is run as a control: its eigenvalues c(alpha) + c(beta) + c(alpha / beta) generate
exactly rule 90's group (proved), so it must be left unresolved at precisely rule 90's shortfalls.

    uv run python examples/parity-lattices-proof/check_triangles.py 3 999 > results.jsonl
"""

from __future__ import annotations

import math
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "xor-periods-proof"))

import sympy  # noqa: E402
from check_odd import Cyclic, primes_of_mersenne, suborder  # noqa: E402

# each rule: the vectors (x, y) of its 2-step polynomial (all with c(x alpha + y beta)), whether it
# has a constant term, and its first line
RULES = {
    "triangle-edge": {"vectors": ((1, 0), (0, 1), (1, 1)), "one": True, "first": (1, 1)},
    "triangle-edge+vertex": {
        "vectors": ((1, 0), (0, 1), (1, 1), (1, -1), (1, 2), (2, 1)),
        "one": False,
        "first": (1, 0),
    },
    "hexagon": {"vectors": ((1, 0), (0, 1), (1, -1)), "one": False, "first": (1, 0)},
}


def eigen_element(ring: Cyclic, rule: str, line: tuple[int, int]) -> int:
    p, q = line
    t = 1 if RULES[rule]["one"] else 0
    for x, y in RULES[rule]["vectors"]:
        k = x * p + y * q
        t ^= ring.z(k) ^ ring.z(-k)
    return t


def lines(N: int, first: tuple[int, int]):
    """The first line, then one primitive vector (p, q) per class under scaling by units mod N,
    the classes with p = 1 first."""
    yield first
    units = [k for k in range(1, N) if math.gcd(k, N) == 1]
    seen = bytearray(N * N)
    for k in units:
        seen[(k * first[0] % N) * N + k * first[1] % N] = 1
    for p in [1] + [p for p in range(N) if p != 1]:
        for q in range(N):
            if seen[p * N + q] or math.gcd(math.gcd(p, q), N) != 1:
                continue
            for k in units:
                seen[(k * p % N) * N + k * q % N] = 1
            yield (p, q)


def check_rule(ring: Cyclic, rule: str, primes: list[int], Q: int) -> dict:
    cache: dict = {}

    def non_residue(line, r) -> bool:
        if line not in cache:
            t = eigen_element(ring, rule, line)
            cache[line] = (t, ring.pow(t, Q))
        t, support = cache[line]
        return ring.pow(t, Q // r) != support

    first = RULES[rule]["first"]
    obstructed, fixed_by, unresolved = [], {}, []
    for r in primes:
        if non_residue(first, r):
            continue
        obstructed.append(r)
        found = next((ln for ln in lines(ring.N, first) if non_residue(ln, r)), None)
        if found:
            fixed_by[r] = list(found)
        else:
            unresolved.append(r)
    return {"first_line_obstructed_by": obstructed, "fixed_by": fixed_by, "unresolved": unresolved}


def check(N: int, rules=("triangle-edge", "triangle-edge+vertex"), seconds: int = 60) -> dict:
    s = suborder(N)
    Q = (1 << s) - 1
    began = time.time()
    primes = primes_of_mersenne(s, seconds)
    complete = primes is not None
    if not complete:
        primes = [r for r in sympy.primerange(3, 10**6) if pow(2, s, r) == 1]
    ring = Cyclic(N)
    out = {"N": N, "s": s, "complete": complete, "primes": len(primes)}
    for rule in rules:
        out[rule] = check_rule(ring, rule, primes, Q)
    out["seconds"] = round(time.time() - began, 1)
    return out


def job(N: int) -> dict:
    try:
        return check(N)
    except Exception as exc:  # reported, never hidden
        return {"N": N, "error": repr(exc)}


if __name__ == "__main__":
    import json
    from multiprocessing import Pool

    low, high = int(sys.argv[1]), int(sys.argv[2])
    odd = [n for n in range(low, high + 1) if n % 2]
    with Pool(4) as pool:
        for result in pool.imap(job, odd):
            print(json.dumps(result), flush=True)
