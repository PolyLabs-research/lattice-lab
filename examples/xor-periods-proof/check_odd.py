"""
The open core of the XOR period law, checked one odd N at a time.

For odd N the torus's longest period is the order of the group generated by the eigenvalues
tau(alpha, beta) = c_alpha + c_beta + c_alpha c_beta (c_alpha = alpha + 1/alpha) over pairs of N-th
roots of unity. They lie in F(2^s), s = sord(N), and the law holds at N exactly when they generate
all of F(2^s)^*: when, for every prime r of Q = 2^s - 1, some eigenvalue is not an r-th power.
See docs/xor-periods-proof.md.

No field needs constructing. The ring R = GF(2)[z]/(z^N - 1) is, for odd N, a product of fields,
one per Frobenius orbit of N-th roots of unity, and the element T = tau(z^p, z^q) of R has the
eigenvalues tau(alpha^p, alpha^q) as its components, for every alpha at once (the line (p, q) of
the torus). Every nonzero component satisfies v^Q = 1, so E = T^Q is the idempotent of T's
support, and some component of T is a nonzero non-r-th power exactly when T^(Q/r) != E.

    uv run python examples/xor-periods-proof/check_odd.py 3 999 > results.jsonl

For each N: the primes of Q (from its cyclotomic parts Phi_d(2), d | s; if they cannot all be
found within the time limit, only primes below 10^6 are checked and `complete` is false), the
primes at which rule 90 (the line (0, 1)) falls short, the line of the 2D rule that supplies a
non-r-th power there, and any prime left unresolved (a counterexample, if `complete`).
"""

from __future__ import annotations

import signal
import time

import numpy as np
import sympy


def suborder(m: int) -> int:
    if m <= 3:
        return 1
    k, v = 1, 2 % m
    while v not in (1, m - 1):
        v, k = v * 2 % m, k + 1
    return k


def _spread(v: int, nbytes: int) -> int:
    """v with each bit moved into its own 16-bit block (little-endian)."""
    bits = np.unpackbits(
        np.frombuffer(v.to_bytes(nbytes, "little"), dtype=np.uint8), bitorder="little"
    )
    return int.from_bytes(bits.astype("<u2").tobytes(), "little")


def clmul(a: int, b: int) -> int:
    """Carry-less (GF(2)[z]) product: spread both factors so that no column sum carries out of its
    16-bit block (it has fewer than 2^16 terms), multiply as integers, keep each block's parity."""
    if not a or not b:
        return 0
    nbytes = (max(a.bit_length(), b.bit_length()) + 7) // 8
    product = _spread(a, nbytes) * _spread(b, nbytes)
    blocks = np.frombuffer(product.to_bytes(32 * nbytes, "little"), dtype="<u2")
    packed = np.packbits((blocks & 1).astype(np.uint8), bitorder="little")
    return int.from_bytes(packed.tobytes(), "little")


class Cyclic:
    """GF(2)[z] / (z^N - 1), elements as N-bit integers."""

    def __init__(self, N: int):
        self.N, self.mask = N, (1 << N) - 1

    def fold(self, p: int) -> int:
        while p >> self.N:
            p = (p & self.mask) ^ (p >> self.N)
        return p

    def mul(self, a: int, b: int) -> int:
        return self.fold(clmul(a, b))

    def pow(self, a: int, e: int) -> int:
        r = 1
        while e:
            if e & 1:
                r = self.mul(r, a)
            a = self.mul(a, a)
            e >>= 1
        return r

    def z(self, k: int) -> int:
        return 1 << (k % self.N)

    def tau(self, p: int, q: int) -> int:
        cx = self.z(p) ^ self.z(-p)
        cy = self.z(q) ^ self.z(-q)
        return cx ^ cy ^ self.mul(cx, cy)


class Timeout(Exception):
    pass


def _alarm(*_):
    raise Timeout()


def primes_of_mersenne(s: int, seconds: int):
    """Prime factors of 2^s - 1 via its cyclotomic parts Phi_d(2), d | s; None on timeout."""
    signal.signal(signal.SIGALRM, _alarm)
    signal.alarm(seconds)
    try:
        found = set()
        for d in sympy.divisors(s):
            found |= set(sympy.factorint(int(sympy.cyclotomic_poly(d, 2))))
        return sorted(found)
    except Timeout:
        return None
    finally:
        signal.alarm(0)


def lines(N: int):
    """Lines (p, q), rule 90's (0, 1) first."""
    yield (0, 1)
    for q in range(2, N):
        yield (1, q)
    for p in range(2, N):
        for q in range(p + 1, N):
            yield (p, q)


def check(N: int, seconds: int = 60) -> dict:
    s = suborder(N)
    Q = (1 << s) - 1
    began = time.time()
    primes = primes_of_mersenne(s, seconds)
    complete = primes is not None
    if not complete:
        primes = [r for r in sympy.primerange(3, 10**6) if pow(2, s, r) == 1]
    ring = Cyclic(N)
    cache: dict = {}

    def non_residue(line, r) -> bool:
        if line not in cache:
            t = ring.tau(*line)
            cache[line] = (t, ring.pow(t, Q))
        t, support = cache[line]
        return ring.pow(t, Q // r) != support

    obstructed, fixed_by, unresolved = [], {}, []
    for r in primes:
        if non_residue((0, 1), r):
            continue
        obstructed.append(r)
        found = next((line for line in lines(N) if line != (0, 1) and non_residue(line, r)), None)
        if found:
            fixed_by[r] = list(found)
        else:
            unresolved.append(r)
    return {
        "N": N,
        "s": s,
        "complete": complete,
        "primes": len(primes),
        "rule90_obstructed_by": obstructed,
        "fixed_by": fixed_by,
        "unresolved": unresolved,
        "seconds": round(time.time() - began, 1),
    }


def job(N: int) -> dict:
    try:
        return check(N)
    except Exception as exc:  # reported, never hidden
        return {"N": N, "error": repr(exc)}


if __name__ == "__main__":
    import json
    import sys
    from multiprocessing import Pool

    low, high = int(sys.argv[1]), int(sys.argv[2])
    odd = [n for n in range(low, high + 1) if n % 2]
    with Pool(4) as pool:
        for result in pool.imap(job, odd):
            print(json.dumps(result), flush=True)
