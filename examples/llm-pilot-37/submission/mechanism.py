"""
Half-Frobenius confinement.  See proposal.md for the statement and the proof.

    condition(f, m) -> q

Notation.  m is odd, d = ord_m(2), s = sord(m); a rule f is symmetric (f(1/x, 1/y) = f), so its
eigenvalues lambda_f(c) = f(zeta^c) lie in F(2^s).  For a lattice vector w, t_w = x^w + x^-w is
rule 90 along w; its eigenvalue at c is the rule-90 eigenvalue t_{w.c} = zeta^{w.c} + zeta^{-w.c}.
G is the rule's symmetry group (the matrices with entries in {-1, 0, 1} that fix f).

  O_v      = prod of t_w over the orbit G v, one w from each pair +-w          (v primitive)
  P_{e,v}  = prod of Psi_e(t_w) over the same w, e odd, gcd(e, m) = 1, where
             D_e(t) = t prod_{1 < e' | e} Psi_e'(t)^2 and D_e(x + 1/x) = x^e + x^-e

The mechanism.  For r in {1, 2}, write f(x^r, y^r) = U * C with U a product of O_v's and
P_{e,v}'s (the "units", stripped from f by exact division) and C the core.  Suppose that for a
product N of O_v's and some g | s, g < s,

    B = C * N  (mod x^m - 1, y^m - 1)   is invariant under (x, y) -> (x^n, y^n),  n = 2^g mod m,

and that on each line {c : w.c = 0 mod m}, w in an orbit of N, the core restricts to a
one-dimensional rule C(z^a, z^b) = H(z + 1/z) with H = t^i prod Psi_e^{k_e} (gcd(e, m) = 1).

Then lambda_B(c) is fixed by the g-th power of Frobenius, so it lies in F(2^g); and the units, N
and the line values are products of rule-90 eigenvalues t_j.  Hence every nonzero eigenvalue of f
lies in the group generated by F(2^g)* and the t_j:

  * if U = N = 1 ("pure": f itself is invariant under the dilation by 2^g on the m-torus),
    every eigenvalue lies in F(2^g), a ((2^s - 1)/(2^g - 1))-th power in F(2^s)*;
  * otherwise, for each prime power p^k (p < PRIME_BOUND) dividing (2^s - 1)/(2^g - 1) such that
    every nonzero t_j is a p^k-th power in F(2^s)* (the confinement of rule 90 itself, the input of
    the splitting mechanism), every eigenvalue of f is a p^k-th power.

The returned q is the product of these factors times (2^d - 1)/(2^s - 1) (eigenvalues lie in
F(2^s)), so that every nonzero eigenvalue of f is a q-th power in F(2^d)*.  It is returned only
when the confinement is proper, i.e. the subgroup of order (2^d - 1)/q is smaller than F(2^s)*;
otherwise condition returns 1.  If f^r is a product of units (C = 1) the t_j alone confine it
(this is the splitting mechanism, kept so that condition's claims are complete).
"""

from __future__ import annotations

import functools
import itertools
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "tools"))

from gf2 import Field  # noqa: E402

PRIME_BOUND = 20000  # primes p tried as factors of the mixed confinement
N_RADIUS = 2  # orbit products O_v in N: primitive v with max(|v_1|, |v_2|) <= N_RADIUS
MAX_N = 3  # at most this many orbit products in N
U_RADIUS = 3  # units: O_v and P_{e,v} with v primitive, max(|v_1|, |v_2|) <= U_RADIUS
U_PSI = (3, 5, 7, 9, 11, 13, 15)
LINE_PSI = 61  # Psi_e with e < LINE_PSI tried on the lines


# ---------------------------------------------------------------- small number theory

def ord2(m: int) -> int:
    j, x = 1, 2 % m
    while x != 1 % m:
        x, j = 2 * x % m, j + 1
    return j


def sord(m: int) -> int:
    j = 1
    while pow(2, j, m) not in (1 % m, (m - 1) % m):
        j += 1
    return j


@functools.cache
def _small_primes(bound: int) -> tuple[int, ...]:
    sieve = bytearray([1]) * (bound + 1)
    sieve[0:2] = b"\x00\x00"
    for i in range(2, int(bound**0.5) + 1):
        if sieve[i]:
            sieve[i * i :: i] = bytearray(len(sieve[i * i :: i]))
    return tuple(i for i in range(bound + 1) if sieve[i])


# ---------------------------------------------------------------- Laurent polynomials over GF(2)
# A two-variable Laurent polynomial is a frozenset of exponent pairs.

ONE = frozenset({(0, 0)})


def pmul(A, B):
    out = set()
    for a0, a1 in A:
        for b0, b1 in B:
            out ^= {(a0 + b0, a1 + b1)}
    return frozenset(out)


def preduce(A, m):
    out = set()
    for p, q in A:
        out ^= {(p % m, q % m)}
    return frozenset(out)


def pscale(A, r):
    return frozenset((r * p, r * q) for p, q in A)


def tfac(w):
    return frozenset({(w[0], w[1]), (-w[0], -w[1])})


def _bbox(A):
    xs = [p for p, _ in A]
    ys = [q for _, q in A]
    return max(xs) - min(xs), max(ys) - min(ys)


def _clmul(a, b):
    """Product of GF(2)[z] polynomials given as int bitmasks."""
    if a.bit_count() > b.bit_count():
        a, b = b, a
    r = 0
    while a:
        low = a & -a
        r ^= b << (low.bit_length() - 1)
        a ^= low
    return r


def _cldivmod(a, b):
    q, db = 0, b.bit_length()
    while a and a.bit_length() >= db:
        sh = a.bit_length() - db
        q ^= 1 << sh
        a ^= b << sh
    return q, a


def pdiv(A, B):
    """The exact quotient A / B of Laurent polynomials over GF(2), or None if B does not divide A.
    (Kronecker substitution to one variable, then a check that the quotient times B is A.)"""
    if not A:
        return frozenset()
    ax, ay = min(p for p, _ in A), min(q for _, q in A)
    bx, by = min(p for p, _ in B), min(q for _, q in B)
    K = max(p for p, _ in A) - ax + 1
    ka = 0
    for p, q in A:
        ka ^= 1 << (p - ax + K * (q - ay))
    kb = 0
    for p, q in B:
        kb ^= 1 << (p - bx + K * (q - by))
    qk, rem = _cldivmod(ka, kb)
    if rem:
        return None
    Q, i = set(), 0
    while qk:
        if qk & 1:
            Q.add((i % K + ax - bx, i // K + ay - by))
        qk >>= 1
        i += 1
    Q = frozenset(Q)
    return Q if pmul(Q, B) == A else None


# ---------------------------------------------------------------- symmetry and orbit products

_MATS = [((a, b), (c, d)) for a, b, c, d in itertools.product((-1, 0, 1), repeat=4)
         if abs(a * d - b * c) == 1]  # fmt: skip


def _apply(M, v):
    return (M[0][0] * v[0] + M[0][1] * v[1], M[1][0] * v[0] + M[1][1] * v[1])


def symmetries(f):
    return tuple(M for M in _MATS if frozenset(_apply(M, v) for v in f) == f)


def _half_orbit(v, group):
    """The orbit G v, and one representative w of each pair +-w in it."""
    orbit = {_apply(M, v) for M in group}
    half, seen = [], set()
    for w in sorted(orbit):
        if (-w[0], -w[1]) not in seen:
            seen.add(w)
            half.append(w)
    return frozenset(orbit), half


def _orbit_reps(group, radius):
    reps, seen = [], set()
    for v in sorted(itertools.product(range(-radius, radius + 1), repeat=2),
                    key=lambda v: (max(abs(v[0]), abs(v[1])), abs(v[0]) + abs(v[1]), v)):
        if v == (0, 0) or v in seen or math.gcd(*v) != 1:
            continue
        seen |= {_apply(M, v) for M in group}
        reps.append(v)
    return reps


# ---------------------------------------------------------------- one variable: Dickson and Psi
# Polynomials in t over GF(2) are int bitmasks (bit i = coefficient of t^i).

@functools.cache
def _dickson(n: int) -> int:
    """D_n(t): x^n + x^-n = D_n(x + 1/x) over GF(2); D_0 = 0 (= 2), D_1 = t."""
    a, b = 0, 0b10
    if n == 0:
        return 0
    for _ in range(n - 1):
        a, b = b, (b << 1) ^ a
    return b


@functools.cache
def _psi(e: int) -> int:
    """Psi_e(t) for odd e >= 3, defined by D_e(t) = t prod_{1 < e' | e} Psi_e'(t)^2."""
    num, rem = _cldivmod(_dickson(e), 0b10)
    assert rem == 0
    for e2 in range(3, e, 2):
        if e % e2 == 0:
            for _ in range(2):
                num, rem = _cldivmod(num, _psi(e2))
                assert rem == 0
    root, i = 0, 0  # num = Psi_e^2; over GF(2) its square root keeps the even coefficients
    while num >> (2 * i):
        if num >> (2 * i) & 1:
            root |= 1 << i
        i += 1
    assert _clmul(root, root) == num
    return root


def _sym_to_t(exps):
    """A one-variable Laurent polynomial (list of exponents, with multiplicity mod 2) that is
    symmetric under z -> 1/z, as a polynomial H(t) with H(z + 1/z) equal to it; None if it is
    not symmetric."""
    par = {}
    for e in exps:
        par[e] = par.get(e, 0) ^ 1
    out = 0
    for e, c in par.items():
        if not c:
            continue
        if par.get(-e, 0) != 1:
            return None
        if e == 0:
            out ^= 1
        elif e > 0:
            out ^= _dickson(e)
    return out


def line_ok(C, w, m) -> bool:
    """On the line {c : w.c = 0 mod m} = {k (w_2, -w_1)}, the core C restricts to H(t_k); whether H
    is t^i times a product of Psi_e (e odd, gcd(e, m) = 1), or zero."""
    c0 = (w[1], -w[0])
    H = _sym_to_t([p * c0[0] + q * c0[1] for p, q in C])
    if H is None:
        return False
    if H == 0:
        return True
    while H & 1 == 0:
        H >>= 1
    for e in range(3, LINE_PSI, 2):
        if H == 1:
            break
        if math.gcd(e, m) != 1:
            continue
        while True:
            q, rem = _cldivmod(H, _psi(e))
            if rem:
                break
            H = q
    return H == 1


# ---------------------------------------------------------------- the confinement of rule 90

@functools.cache
def _rule90_powers(m: int) -> dict[int, int]:
    """{p: p^k} for the odd primes p < PRIME_BOUND dividing 2^s - 1, with p^k the largest power of
    p such that every nonzero t_j = zeta^j + zeta^-j (j in Z/m) is a p^k-th power in F(2^s)*.
    This is rule 90's own confinement at m (the input of the splitting mechanism)."""
    s = sord(m)
    Ns = 2**s - 1
    primes = [p for p in _small_primes(PRIME_BOUND) if p > 2 and Ns % p == 0]
    if not primes:
        return {}
    F = Field(m)
    reps, seen = [], set()
    for j in range(1, m):
        if j not in seen:
            x = j
            while x not in seen:
                seen |= {x, m - x}
                x = 2 * x % m
            reps.append(j)
    tvals = [v for v in (F.pow(F.zeta, j) ^ F.pow(F.zeta, m - j) for j in reps) if v]
    out = {}
    for p in primes:
        pk = 1
        while Ns % (pk * p) == 0 and all(F.pow(v, Ns // (pk * p)) == 1 for v in tvals):
            pk *= p
        out[p] = pk
    return out


@functools.cache
def _levels(m: int):
    """For each proper divisor g of s: (g, n = 2^g mod m, q_pure, q_mixed), confinement factors in
    F(2^s)* for values in F(2^g) alone and in <F(2^g)*, t_j>."""
    s = sord(m)
    Ns = 2**s - 1
    r90 = _rule90_powers(m)
    out = []
    for g in range(1, s):
        if s % g:
            continue
        M = Ns // (2**g - 1)
        qmix = 1
        for p, pk in r90.items():
            while pk > 1 and M % pk:
                pk //= p
            qmix *= pk
        out.append((g, pow(2, g, m), M, qmix))
    return out


# ---------------------------------------------------------------- the search

@functools.cache
def _units(group, m):
    units = []
    for v in _orbit_reps(group, U_RADIUS):
        _, half = _half_orbit(v, group)
        P = ONE
        for w in half:
            P = pmul(P, tfac(w))
        units.append((("O", v), P, _bbox(P)))
        for e in U_PSI:
            if math.gcd(e, m) != 1:
                continue
            P = ONE
            for w in half:
                term, power, T, i = frozenset(), ONE, _psi(e), 0
                while T >> i:
                    if T >> i & 1:
                        term = term ^ power
                    power = pmul(power, tfac(w))
                    i += 1
                P = pmul(P, term)
            units.append((("P%d" % e, v), P, _bbox(P)))
    return units


@functools.cache
def _nreps(group):
    out = []
    for v in _orbit_reps(group, N_RADIUS):
        orbit, half = _half_orbit(v, group)
        P = ONE
        for w in half:
            P = pmul(P, tfac(w))
        out.append((v, P, orbit))
    return tuple(out)


def _strip(F, units):
    stripped = []
    changed = True
    while changed and F != ONE:
        changed = False
        ex, ey = _bbox(F)
        for name, U, (ux, uy) in units:
            if ux > ex or uy > ey:
                continue
            Q = pdiv(F, U)
            if Q is not None:
                F, changed = Q, True
                stripped.append(name)
                break
    return F, stripped


def _search(Bm, C, m, levels, nreps, combo, lines, start, pure_ok, best):
    """Depth first over N = O_v1 ... O_vk (k <= MAX_N); Bm = C N mod m.  Updates best."""
    for g, n, qpure, qmix in levels:
        q = qpure if (pure_ok and not combo) else qmix
        if q <= best[0]:
            continue
        if any(((n * p) % m, (n * q) % m) not in Bm for p, q in Bm):
            continue
        if all(line_ok(C, w, m) for w in lines):
            best[:] = [q, g, combo, Bm]
    if len(combo) == MAX_N:
        return
    for i in range(start, len(nreps)):
        v, P, orbit = nreps[i]
        _search(preduce(pmul(Bm, P), m), C, m, levels, nreps, combo + (v,), lines | orbit, i,
                pure_ok, best)


def explain(f, m):
    """The best witness found, as a dict, or None."""
    f = frozenset(map(tuple, f))
    if m < 3 or m % 2 == 0 or not f or frozenset((-p, -q) for p, q in f) != f:
        return None
    s, d = sord(m), ord2(m)
    lift = (2**d - 1) // (2**s - 1)
    levels = _levels(m)
    if not levels:
        return None
    r90 = math.prod(_rule90_powers(m).values())
    group = symmetries(f)
    units = _units(group, m)
    best = [1, None, None, None]
    witness = None
    # pure case on f itself: f invariant under the dilation by 2^g mod m
    fm = preduce(f, m)
    for g, n, qpure, _ in levels:
        if qpure > best[0] and all(((n * p) % m, (n * q) % m) in fm for p, q in fm):
            best = [qpure, g, (), fm]
            witness = dict(r=1, units=[], core=f)
    for r in (1, 2):
        F = pscale(f, r)
        C, stripped = _strip(F, units)
        if C == ONE:
            if r90 > best[0]:
                best = [r90, None, (), ONE]
                witness = dict(r=r, units=stripped, core=C)
            continue
        before = best[0]
        _search(preduce(C, m), C, m, levels, _nreps(group), (), frozenset(), 0,
                not stripped, best)
        if best[0] > before:
            witness = dict(r=r, units=stripped, core=C)
    if best[0] == 1:
        return None
    witness.update(q=best[0] * lift, q_s=best[0], g=best[1], N=best[2], B=best[3])
    return witness


def condition(f, m: int) -> int:
    w = explain(f, m)
    return w["q"] if w else 1
