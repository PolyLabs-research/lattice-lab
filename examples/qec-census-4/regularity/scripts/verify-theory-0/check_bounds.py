"""Independent check of the 'theory' claim against the census data.

1. Recompute the explicit Bravyi-Terhal-variant constants (Arnault et al. 2502.04995 Thm 3.6/4.1,
   Postema-Kokkelmans 2502.17052 Thm 2.18) under both conventions for 'n'
   (n = code length 2lm, or n = |G| = lm = number of lattice sites).
2. Compare with the census frontier (deduplicated by group isomorphism class).
3. Structural check of each frontier code: subgroups generated by the normalised supports of A
   and B (G_a, G_b); hypergraph-product test (G_a + G_b = G, G_a cap G_b = 0); HGP ceiling
   d <= min(|G_a|, |G_b|) <= sqrt(n/2); and whether the frontier ever exceeds that ceiling.
"""
import json, math, sys
from math import gcd

DATA = sys.argv[1]
D = json.load(open(DATA))
E = D["entries"]

# ---- 1. constants ----
Dim = 4
gamma4 = math.sqrt(2.0)  # Hermite constant gamma_4 = 4^{1/4}... gamma_4^4 = 4 -> gamma_4 = sqrt 2
C = 2 * math.sqrt(gamma4) * (math.sqrt(Dim) + 4 * 1)  # m=2 qubits per site, rho=1
thr = (8 * 1 * math.sqrt(gamma4)) ** Dim               # n^{1/D} >= 8 rho sqrt(gamma_D)
C_slide = 2 * (4 + Dim) * math.sqrt(gamma4)            # slide variant 2(4+D)sqrt(gamma_D), if that reading
print(f"gamma_4 = {gamma4:.6f}, sqrt(gamma_4) = {math.sqrt(gamma4):.6f}")
print(f"C = 2 sqrt(g4)(sqrt4+4) = {C:.4f};  threshold (8 sqrt g4)^4 = {thr:.1f}")
print(f"C^4 (crossover where C N^(3/4) = N) = {C**4:.0f}")
print(f"length-convention C n^(3/4) < n  for n > {C**4:.0f}")
# site convention: d <= C (n/2)^{3/4}; valid for n/2 >= thr  -> n >= 2 thr
print(f"site convention: d <= C (n/2)^(3/4) = {C/2**0.75:.4f} n^(3/4); valid for n >= {2*thr:.0f}")
print(f"site convention beats trivial d<=n for n > {(C/2**0.75)**4:.0f}")
print(f"slide-variant constant 2(4+D)sqrt(g4) = {C_slide:.4f}")

# ---- 2. frontier vs bound ----
def grp_key(l, m):
    g = gcd(l, m)
    return (g, l * m // g)

best = {}  # (group, k) -> entry with max d
for e in E:
    key = (grp_key(e["l"], e["m"]), e["k"])
    if key not in best or e["d"] > best[key]["d"]:
        best[key] = e
print(f"\nentries {len(E)}, distinct (group,k) {len(best)}")
nmax = {}
for e in E:
    nmax[e["n"]] = max(nmax.get(e["n"], 0), e["d"])
worst = max(nmax.items(), key=lambda t: t[1] / (C * t[0] ** 0.75))
print("max over n of d/(C n^.75) = %.4f at n=%d d=%d" % (worst[1] / (C * worst[0] ** 0.75), worst[0], worst[1]))
worst2 = max(nmax.items(), key=lambda t: t[1] / (C * (t[0] / 2) ** 0.75))
print("max over n of d/(C (n/2)^.75) = %.4f at n=%d d=%d" % (worst2[1] / (C * (worst2[0] / 2) ** 0.75), worst2[0], worst2[1]))
for n in (100, 200, 300, 400):
    print(f"  n={n}: C n^.75={C*n**.75:.0f}  C(n/2)^.75={C*(n/2)**.75:.0f}  vs n={n}; census max d at n<= {n}: {max(d for nn,d in nmax.items() if nn<=n)}")

# ---- 3. structure ----
def subgroup(gens, l, m):
    S = {(0, 0)}
    frontier = [(0, 0)]
    while frontier:
        new = []
        for (a, b) in frontier:
            for (x, y) in gens:
                for s in (1, -1):
                    p = ((a + s * x) % l, (b + s * y) % m)
                    if p not in S:
                        S.add(p); new.append(p)
        frontier = new
    return S

def norm_gens(P, l, m):
    a0, b0 = P[0]
    return [((a - a0) % l, (b - b0) % m) for (a, b) in P[1:]]

rows = []
noAB = 0
for e in E:
    if not e.get("A") or not e.get("B"):
        noAB += 1; continue
    l, m = e["l"], e["m"]
    Ga = subgroup(norm_gens(e["A"], l, m), l, m)
    Gb = subgroup(norm_gens(e["B"], l, m), l, m)
    inter = len(Ga & Gb)
    full = subgroup(norm_gens(e["A"], l, m) + norm_gens(e["B"], l, m), l, m)
    hgp = (inter == 1 and len(Ga) * len(Gb) == l * m)
    rows.append(dict(l=l, m=m, n=e["n"], k=e["k"], d=e["d"], Ga=len(Ga), Gb=len(Gb), inter=inter,
                     conn=(len(full) == l * m), hgp=hgp, stage=e["stage"]))

print(f"\nentries without A/B witness polynomials: {noAB}")
print(f"connected (G_a+G_b=G): {sum(r['conn'] for r in rows)} of {len(rows)}")
print(f"HGP-type (G_a cap G_b=0, |G_a||G_b|=|G|): {sum(r['hgp'] for r in rows)} of {len(rows)}")
viol = [r for r in rows if r["d"] > min(r["Ga"], r["Gb"])]
print(f"d > min(|G_a|,|G_b|): {len(viol)} entries")
for r in viol[:10]:
    print("   ", r)
small = [r for r in rows if min(r["Ga"], r["Gb"]) < r["l"] * r["m"]]
print(f"entries with a proper G_a or G_b: {len(small)}")
for r in small[:12]:
    print("   ", r)
above = [r for r in rows if r["d"] > math.sqrt(r["n"] / 2)]
print(f"entries with d > sqrt(n/2) (above any HGP code on that torus): {len(above)} of {len(rows)}")
# HGP-type entries: d vs their ceiling
for r in rows:
    if r["hgp"]:
        print("  HGP entry:", r, " ceiling min(|Ga|,|Gb|) =", min(r['Ga'], r['Gb']))
# band maxima of d/sqrt(n) for context (dedup irrelevant for maxima)
print()
for lo in range(0, 400, 50):
    sel = [(e["d"] / math.sqrt(e["n"]), e["n"], e["d"]) for e in E if lo < e["n"] <= lo + 50]
    if sel:
        mx = max(sel)
        print(f"band ({lo},{lo+50}]: max d/sqrt n = {mx[0]:.3f} (n={mx[1]}, d={mx[2]}); "
              f"d/(C n^.75) = {mx[2]/(C*mx[1]**.75):.4f}")
