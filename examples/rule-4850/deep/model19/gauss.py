"""Gauss sums of conductor 37 and 19 in characteristic 2, inside F(2^18) (ff18 model), and their link to
the resolvents R_k.  For a character chi of (Z/p)*/{+-1} (cyclic of order 18, generated by 2) of odd order
d | 9, chi(2) = w9^(9/d):
   G37(chi) = sum_{e=0}^{17} chi(2)^e t_{2^e},      G19(chi) = sum_{e=0}^{17} chi(2)^e (z19^{2^e} + z19^{-2^e}) / ...
(the full sums over (Z/p)*, paired a <-> -a).  Proof sketch checked here: G(chi)^{2^6} = chi(2)^{-6*64}... i.e.
G^63 = chi(2)^3, and G^513 = 1, so G is a primitive 27th root of 1 when chi has order 9 (2 a primitive root)."""
import json
import ff18 as F
from resolvents import R

T = F.tvec()
z27 = F.zeta27()
w9 = F.pw(z27, 3)
z19 = F.z19pows()
out = {}
for name, base in (('G37', lambda e: T[pow(2, e, 37)]), ('G19', lambda e: z19[pow(2, e, 19)])):
    for order in (3, 9):
        c = F.pw(w9, 9 // order)  # chi(2)
        G = 0
        for e in range(18):
            G ^= F.mul(F.pw(c, e), base(e))
        rec = dict(order_chi=order, v27=F.v27(G), in_mu27=F.pw(G, 27) == 1, order=None)
        for o in (1, 3, 9, 27):
            if F.pw(G, o) == 1:
                rec['order'] = o; break
        rec['G^63 == chi(2)^3'] = F.pw(G, 63) == F.pw(c, 3)
        out['%s_chi%d' % (name, order)] = rec
        print(name, rec)
# relation G37(chi) = sum_{e=0}^{5} chi(2)^e R_k(t_{2^e}),  w^k = chi(2^6)
w = F.pw(z27, 9)
c = w9
k = next(k for k in range(3) if F.pw(w, k) == F.pw(c, 6))
G = 0
for e in range(18):
    G ^= F.mul(F.pw(c, e), T[pow(2, e, 37)])
G2 = 0
for e in range(6):
    G2 ^= F.mul(F.pw(c, e), R(k, T[pow(2, e, 37)]))
out['G37 = sum_e chi(2)^e R_k(t_2^e)'] = G == G2
print('G37(chi9) = sum_{e<6} chi(2)^e R_k(t_{2^e}) with w^k = chi(2^6):', G == G2)
json.dump(out, open('gauss.json', 'w'), indent=1)
