"""Step 7: character formulas for the 27th-power obstruction digit of 4850 and its relatives.

A D4-invariant, scaling-odd function on characters has no single-form expression chi(F(j, k)):
the D4 semi-invariant binary forms (generated by j^2 + k^2, jk, j^2 - k^2) all have even degree, and
chi(F(uc)) = chi(u)^deg F chi(F(c)) must be odd.  So every candidate is an orbit sum
      G_F(c) = sum_{g in D4} chi(F(g c))     (F of odd degree).
Dictionary (fixed before looking at the match):
  deg 1: F = a j + b k, |a|, |b| <= 6            (the ten S_O; weight-1 patterns)
  deg 3: F = L1 L2 L3, L_i distinct among the six "natural" lines j, k, j + k, j - k, j + 6k, j - 6k
         (6^2 = -1, so j +- 6k are the isotropic lines of j^2 + k^2)
  deg 3: F = Q * L, Q in {j^2 + k^2, jk, j^2 - k^2, j^2 + jk + k^2, j^2 - jk + k^2, j^2 + 3k^2, 2j^2 + k^2},
         L = a j + b k with |a|, |b| <= 3
  deg 5: F = (j^2 + k^2) * L1 L2 L3 and jk(j^2 - k^2) * L, L's from the natural lines
Target: d (digit2 per class, census order) for each rule; matches are tested
  (i) exactly, d = +-G;  (ii) modulo the unit-adjustable orbits (axis, diagonal) and the diagonal
  class (the freedom seen across the relatives): d = +-G + a S_axis + b S_diag + c delta_diag.
Null: the fraction of uniform random digit vectors matched in the same way.  Writes step7_formulas.json.
"""
import itertools
import json

import numpy as np

import tlib
from tlib import M, chi
import sbasis

D4 = sbasis.D4
REPS = tlib.CENSUS_REPS


def orbit_sum(F):
    vals = []
    for (j, k) in REPS:
        s = 0
        for g in D4:
            a, b = g(j, k)
            s += chi[F(a, b) % M]
        vals.append(s % 3)
    return tuple(vals)


def dictionary():
    D = {}
    nat = {"j": (1, 0), "k": (0, 1), "j+k": (1, 1), "j-k": (1, -1), "j+6k": (1, 6), "j-6k": (1, -6)}
    for a in range(-6, 7):
        for b in range(-6, 7):
            if (a, b) != (0, 0):
                D.setdefault(orbit_sum(lambda j, k, a=a, b=b: a * j + b * k), f"lin({a},{b})")
    for (n1, l1), (n2, l2), (n3, l3) in itertools.combinations(nat.items(), 3):
        F = lambda j, k, l1=l1, l2=l2, l3=l3: (l1[0] * j + l1[1] * k) * (l2[0] * j + l2[1] * k) * (l3[0] * j + l3[1] * k)
        D.setdefault(orbit_sum(F), f"({n1})({n2})({n3})")
    quads = {"j2+k2": lambda j, k: j * j + k * k, "jk": lambda j, k: j * k, "j2-k2": lambda j, k: j * j - k * k,
             "j2+jk+k2": lambda j, k: j * j + j * k + k * k, "j2-jk+k2": lambda j, k: j * j - j * k + k * k,
             "j2+3k2": lambda j, k: j * j + 3 * k * k, "2j2+k2": lambda j, k: 2 * j * j + k * k}
    for qn, Q in quads.items():
        for a in range(-3, 4):
            for b in range(-3, 4):
                if (a, b) != (0, 0):
                    F = lambda j, k, Q=Q, a=a, b=b: Q(j, k) * (a * j + b * k)
                    D.setdefault(orbit_sum(F), f"{qn}*({a},{b})")
    for (n1, l1), (n2, l2), (n3, l3) in itertools.combinations(nat.items(), 3):
        F = lambda j, k, l1=l1, l2=l2, l3=l3: (j * j + k * k) * (l1[0] * j + l1[1] * k) * (l2[0] * j + l2[1] * k) * (l3[0] * j + l3[1] * k)
        D.setdefault(orbit_sum(F), f"(j2+k2)({n1})({n2})({n3})")
    for n1, l1 in nat.items():
        F = lambda j, k, l1=l1: j * k * (j * j - k * k) * (l1[0] * j + l1[1] * k)
        D.setdefault(orbit_sum(F), f"jk(j2-k2)({n1})")
    D.pop(tuple([0] * 11), None)
    return D


def adjust_set():
    S = sbasis.S_matrix()
    axis, diag = S[0], S[1]
    delta = np.zeros(11, dtype=np.int64)
    delta[1] = 1
    out = []
    for a, b, c in itertools.product(range(3), repeat=3):
        out.append(((a * axis + b * diag + c * delta) % 3, (a, b, c)))
    return out


def match(d, D, adj):
    d = np.asarray(d) % 3
    exact, loose = [], []
    for G, name in D.items():
        G = np.array(G)
        for s in (1, 2):
            if np.array_equal((s * G) % 3, d):
                exact.append((name, s))
            for v, abc in adj:
                if np.array_equal((s * G + v) % 3, d):
                    loose.append((name, s, abc))
    return exact, loose


if __name__ == "__main__":
    D = dictionary()
    adj = adjust_set()
    print("dictionary: %d distinct nonzero class patterns" % len(D))
    st1 = json.load(open("step1_digits.json"))
    out = {"dictionary_size": len(D)}
    for n in ("4850", "482758", "10491524", "8438150", "43250486", "20982139", "178279803"):
        d = st1[n]["class_digit2"]
        ex, lo = match(d, D, adj)
        out[n] = dict(digit2=d, exact=ex, loose=lo[:20], n_loose=len(lo))
        print(n, d, "exact:", ex, "| modulo axis/diag/delta_diag:", len(lo), lo[:6])
    # null
    rng = np.random.default_rng(11)
    S = sbasis.S_matrix()
    ne = nl = 0
    NS = 3000
    for _ in range(NS):
        eps = rng.integers(0, 3, 11)
        eps[6] = 0
        d = (eps @ S) % 3
        ex, lo = match(d, D, adj)
        ne += bool(ex)
        nl += bool(lo)
    out["null_exact_rate"] = ne / NS
    out["null_loose_rate"] = nl / NS
    print("null (uniform digit vectors, %d): exact match rate %.4f, loose match rate %.4f" % (NS, ne / NS, nl / NS))
    json.dump(out, open("step7_formulas.json", "w"), indent=1, default=str)
