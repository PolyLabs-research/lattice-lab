def _dilation(f):
    """(p, h) with f = h(x^p, y^p) for the largest such p > 1, or None."""
    g = 0
    for a, b in f:
        g = math.gcd(g, math.gcd(abs(a), abs(b)))
    if g <= 1:
        return None
    return g, frozenset((a // g, b // g) for a, b in f)


def explain(f, m: int):
    f = frozenset(map(tuple, f))
    if m < 3 or m % 2 == 0 or not f:
        return None
    symmetric = frozenset((-p, -q) for p, q in f) == f
    if not symmetric:
        return None
    s, d = sord(m), ord2(m)
    Ns = 2**s - 1
    R = (2**d - 1) // Ns
    found = []
    q_s = 1
    sa = _theorem_a(f, m)
    sb, wb = _theorem_b(f, m)
    for p in _primes_of_s(m):
        k = max(sa.get(p, 0), sb.get(p, 0))
        if k:
            q_s *= p**k
    if sa:
        found.append(("units times a power", sa))
    if sb:
        found.append(("half-Frobenius", sb, {k: v for k, v in wb.items() if k != "core"}))
    q = q_s * R
    dil = _dilation(f)
    if dil is not None:
        p, h = dil
        g = math.gcd(p, m)
        if g > 1:
            # f = h(x^g, y^g): eigenvalues of f at m are those of h at m/g (zeta^g primitive)
            h = frozenset((a * (p // g), b * (p // g)) for a, b in h)
            m2 = m // g
            if m2 > 1:
                q2 = condition(h, m2)
                d2 = ord2(m2)
                lift = (2**d - 1) // (2**d2 - 1)
                q = math.lcm(q, q2 * lift)
                found.append(("dilation", g, q2))
    if USE_PREVIOUS:
        qa, wa = certificate.twisted_pair(f, m)
        if qa > 1:
            q = math.lcm(q, qa)
            found.append(("twisted pair", wa))
    if q == R or q == 1:
        return None
    return dict(q=q, found=found)


def condition(f, m: int) -> int:
    w = explain(f, m)
    return w["q"] if w else 1


