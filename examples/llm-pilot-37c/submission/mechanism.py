"""
Unit-exponent bookkeeping: q-th power confinement from the exact exponents of the line units.
See proposal.md for the statements and the proofs.

    condition(f, m) -> q        every nonzero eigenvalue of f at m is a q-th power in F(2^d)*,
                                d = ord_m(2); 1 if no claim

Notation.  m odd, d = ord_m(2), s = sord(m), R = (2^d - 1)/(2^s - 1).  A symmetric rule f has its
eigenvalues lambda_f(c) = f(zeta^c) in F(2^s).  t_j = zeta^j + zeta^-j are rule 90's eigenvalues,
and for a prime p, q'_p = p^k' is the largest power of p such that every nonzero t_j is a q'_p-th
power in F(2^s)* (rule 90's own confinement at m, read off its values: the only field computation).
For a primitive w, X_w = x^w1 y^w2 and t_w = X_w + 1/X_w; Phi_e is the e-th cyclotomic polynomial
and Psi_e(z + 1/z) = z^(-phi(e)/2) Phi_e(z).  Call e "representable at m" if every divisor e' > 1
of e is prime to m and congruent to +-2^a(e') (mod m): then Psi_e(t_j)^2 = t_j^A_e for j != 0,
A_e = sum_{e'|e} mu(e/e') 2^a(e'), and (1 + zeta^j)^2 = zeta^j t_j.

A product of line units along a direction w, Phi_1(X_w)^k1 prod_e Phi_e(X_w)^ke (e representable),
has at c = (j, k) the value (monomial) * V, with V^2 = t_(w.c)^E_w, E_w = k1 + sum_e ke A_e.  So the
unit is a p^k-th power wherever p^k | q'_p E_w: the exponent E_w is what matters, and it is exact.
At m = 37 every e is representable (2 is a primitive root), q'_3 = 3, and for example
(1 + a)(1 + b) = Phi_3(x) Phi_3(y)/(xy) has E = A_3 = 2^26 - 1 = 3 * 22369621 in each axis
direction: every value a ninth power although rule 90 gives only cubes.

Theorem A (units times a power).  f = x^v * prod_(w,e) Phi_e(X_w)^k(w,e) * h^Q exactly (h = 1
allowed).  Then every nonzero eigenvalue of f is a p^k-th power in F(2^s)* for p^k | 2^s - 1 with
p^k | Q (if h != 1), p^k | q'_p E_w for every direction w, and p^k | q'_p k(w,e) for every
non-representable unit with gcd(e, m) = 1 (its values lie in the group generated by the t_j).

Theorem B (half-Frobenius with bookkeeping).  f^(r) = U * C exactly (r in {1, 2}, U a product of
line units as above, C the core), and for a product N of orbit units (t_w and Psi_e(t_w) products
over the symmetry orbit of a direction) and a proper divisor g of s,

    B = C * N  (mod x^m - 1, y^m - 1)  is invariant under (x, y) -> (x^n, y^n), n = 2^g mod m.

Then lambda_B lies in F(2^g), a ((2^s-1)/(2^g-1))-th power, and lambda_f(rc) = lambda_U lambda_B /
lambda_N.  Every nonzero eigenvalue of f is a p^k-th power for p^k | (2^s-1)/(2^g-1) with
p^k | q'_p E_w for the exponents E_w of U/N (combined per direction), and, on the lines where N
vanishes, p^k | q'_p A for the total exponent A of U times the one-variable restriction of C
(which must be t^i prod Psi_e^ke with representable e).  U = N = 1 is the pure case: f itself
invariant, every eigenvalue in F(2^g).

Dilations: f = h(x^p, y^p) with p | m gives the eigenvalues of h at m/p (recursively).  The exact
twisted pairs and cube certificates of tools/certificate.py and the unit-times-power condition of
tools/unitpower.py are consulted and the lcm is returned.  No eigenvalue of f is computed.
"""

