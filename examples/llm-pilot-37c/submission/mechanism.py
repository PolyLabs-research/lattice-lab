# ---------------------------------------------------------------- arithmetic

def _vp(n: int, p: int) -> int:
    n = abs(n)
    v = 0
    while n and n % p == 0:
        n //= p
        v += 1
    return v


@functools.cache
def _pow2_log(m: int) -> dict:
    """{r: a} with r = +-2^a mod m, the least such a."""
    out, x = {}, 1 % m
    for a in range(ord2(m)):
        out.setdefault(x, a)
        out.setdefault((-x) % m, a)
        x = 2 * x % m
    return out


def _mobius(n: int) -> int:
    out, p = 1, 2
    while p * p <= n:
        if n % p == 0:
            n //= p
            if n % p == 0:
                return 0
            out = -out
        p += 1
    return -out if n > 1 else out


@functools.cache
def _A(e: int, m: int):
    """A_e if e is representable at m (every divisor e' > 1 prime to m and +-2^a mod m), else None.
    For e = 1 (the unit 1 + X_w): 1."""
    if e == 1:
        return 1
    logs = _pow2_log(m)
    divs = [q for q in range(1, e + 1) if e % q == 0]
    if any(math.gcd(q, m) != 1 or q % m not in logs for q in divs[1:]):
        return None
    return sum(_mobius(e // q) * 2 ** (logs[q % m] if q > 1 else 0) for q in divs)


def _is_prime(n: int) -> bool:
    return n > 1 and all(n % p for p in range(2, int(n**0.5) + 1))


@functools.cache
def _primes_of_s(m: int):
    s = sord(m)
    Ns = 2**s - 1
    return tuple(p for p in _small_primes(PRIME_BOUND) if p > 2 and Ns % p == 0)


# ---------------------------------------------------------------- exponents of unit products

class _Book:
    """Exponent bookkeeping for a product of line units: E[w] (combined, representable) and
    sep[(w, e)] (non-representable, gcd(e, m) = 1 or e prime), per direction w (up to sign).
    Directions are stored as primitive vectors with the sign normalised."""

    def __init__(self, m):
        self.m = m
        self.E = {}
        self.sep = {}
        self.bad = False  # a unit whose values are not known to lie in <t_j>

    @staticmethod
    def _norm(w):
        a, b = w
        if a < 0 or (a == 0 and b < 0):
            a, b = -a, -b
        return (a, b)

    def add(self, w, e, k):
        """Phi_e(X_w)^k (e = 1: 1 + X_w; as a function this is a power of t_(w.c))."""
        if k == 0:
            return
        w = self._norm(w)
        A = _A(e, self.m)
        if A is not None:
            self.E[w] = self.E.get(w, 0) + k * A
        elif math.gcd(e, self.m) == 1 or _is_prime(e):
            self.sep[(w, e)] = self.sep.get((w, e), 0) + k
        else:
            self.bad = True

    def add_t(self, w, k):
        """t_w^k = X_w^-k (1 + X_w)^(2k)."""
        self.add(w, 1, 2 * k)

    def add_psi(self, w, e, k):
        """Psi_e(t_w)^k = (monomial) Phi_e(X_w)^k."""
        self.add(w, e, k)

    def power(self, p, k90, cap):
        """The largest k <= cap with p^k | q'_p E for every exponent."""
        if self.bad:
            return 0
        k = cap
        for ew in self.E.values():
            if ew != 0:
                k = min(k, k90 + _vp(ew, p))
        for b in self.sep.values():
            if b != 0:
                k = min(k, k90 + _vp(b, p))
        return k


# ---------------------------------------------------------------- Theorem A

def _center(C):
    """The symmetric translate x^u C of a Laurent polynomial symmetric about an integral point, else None."""
    if not C:
        return None
    xs = [p for p, _ in C]
    ys = [q for _, q in C]
    sx, sy = min(xs) + max(xs), min(ys) + max(ys)
    if sx % 2 or sy % 2:
        return None
    S = frozenset((p - sx // 2, q - sy // 2) for p, q in C)
    return S if frozenset((-p, -q) for p, q in S) == S else None



def _theorem_a(f, m, depth=0):
    """{p: k} from the exact factorisation f = monomial * line units * core, core = h^Q."""
    groups, core = unitpower.structure(f)
    book = _Book(m)
    for (w, e), (mults, npieces) in groups.items():
        ms = list(mults) + [0] * (npieces - len(mults))
        k = min(ms)
        if any(x != k for x in ms):
            # a partial product of the factors of Phi_e(X_w) is left in the core: no structure
            return {}
        book.add(w, e, k)
    out = {}
    if len(core) > 1:
        Q = unitpower._core_gcd(core)
        if Q <= 1:
            return {}
    s = sord(m)
    Ns = 2**s - 1
    r90 = _rule90_powers(m)
    # the core h^Q: its Q-th root h may itself be confined (recursively), e.g. W^3 with W cube-valued
    hscore = {}
    if len(core) > 1 and depth < 2:
        Qs = {p: _vp(Q, p) for p in _primes_of_s(m) if Q % p == 0}
        for p, kq in Qs.items():
            h = unitpower._qth_root(core, p**kq)
            if h is None:
                continue
            h = _center(h)
            if h is None or len(h) <= 1:
                continue
            sub = _scores(h, m, depth + 1)
            hscore[p] = sub.get(p, 0)
    for p in _primes_of_s(m):
        cap = _vp(Ns, p)
        k = book.power(p, _vp(r90.get(p, 1), p), cap)
        if len(core) > 1:
            kq = _vp(Q, p)
            if kq == 0:
                k = 0
            else:
                if not unitpower._core_root_ok(core, p**kq):
                    k = 0
                else:
                    k = min(k, kq + hscore.get(p, 0), cap)
        if k:
            out[p] = k
    return out


def _scores(f, m, depth=0):
    """{p: k} for a symmetric rule, the best of Theorems A and B."""
    sa = _theorem_a(f, m, depth)
    sb, _ = _theorem_b(f, m)
    return {p: max(sa.get(p, 0), sb.get(p, 0)) for p in set(sa) | set(sb)}


# ---------------------------------------------------------------- Theorem B

class _Probe:
    """x^(p, r) -> z^(v1 p + v2 r) mod z^m - 1: a ring homomorphism commuting with dilations.  Images
    are numpy 0/1 arrays of length m; products are cyclic convolutions mod 2."""

    def __init__(self, v, m):
        self.v, self.m = v, m

    def image(self, P):
        x = np.zeros(self.m, dtype=np.int64)
        for p, r in P:
            x[(self.v[0] * p + self.v[1] * r) % self.m] ^= 1
        return x

    def mul(self, a, b):
        c = np.convolve(a, b)
        out = c[: self.m].copy()
        out[: len(c) - self.m] += c[self.m :]
        return out & 1

    @staticmethod
    def invariant(x, idx):
        return np.array_equal(x[idx], x)


@functools.cache
def _probe_dirs(dirs, m, k=2):
    """k directions v with v.w != 0 mod m for every atom direction w (no atom image vanishes), on lines
    that are inequivalent under the lattice symmetries and scalars mod m (independent tests)."""
    out = []

    def line_class(v):
        a, b = v
        cls = set()
        for p, q in ((a, b), (b, a)):
            for sp in (1, -1):
                for sq in (1, -1):
                    x, y = (sp * p) % m, (sq * q) % m
                    for lam in range(1, m):
                        cls.add(((lam * x) % m, (lam * y) % m))
        return frozenset(cls)

    classes = []
    for v in sorted(itertools.product(range(-9, 10), repeat=2), key=lambda v: (abs(v[0]) + abs(v[1]), v)):
        if v == (0, 0) or math.gcd(v[0], v[1]) != 1 or v < (0, 0):
            continue
        if not all((v[0] * w[0] + v[1] * w[1]) % m for w in dirs):
            continue
        c = line_class(v)
        if any((v[0] % m, v[1] % m) in c2 for c2 in classes):
            continue
        out.append(v)
        classes.append(c)
        if len(out) == k:
            break
    while len(out) < k:
        out.append((1, len(out)))
    return tuple(out[:k])


def _dense(P, m):
    D = np.zeros((m, m), dtype=np.uint8)
    for p, r in P:
        D[p % m, r % m] ^= 1
    return D


def _dense_mul(A, B):
    C = np.fft.ifft2(np.fft.fft2(A.astype(np.float64)) * np.fft.fft2(B.astype(np.float64))).real
    return (np.rint(C).astype(np.int64) & 1).astype(np.uint8)


def _invariant(D, n, m) -> bool:
    idx = (np.arange(m) * n) % m
    return np.array_equal(D[np.ix_(idx, idx)], D)


@functools.cache
def _natoms(group, m):
    """Orbit units for N: (name, polynomial, half-orbit, kind, e)."""
    out = []
    for v in _orbit_reps(group, N_RADIUS):
        _, half = _half_orbit(v, group)
        P = ONE
        for w in half:
            P = pmul(P, tfac(w))
        out.append((("O", v), P, tuple(half), "O", 1))
        for e in N_PSI + (N_PSI_AXIS if max(abs(v[0]), abs(v[1])) <= 1 and m <= MAX_N_SIZE else ()):
            if math.gcd(e, m) != 1:
                continue
            P = ONE
            for w in half:
                term, power, T, i = frozenset(), ONE, _psi(e), 0
                while T >> i:
                    if T >> i & 1:
                        term = term ^ power
                    power = pmul(power, tfac(w))
                    i += 1
                P = pmul(P, term)
            out.append((("P%d" % e, v), P, tuple(half), "P", e))
    return tuple(out)


def _line_H(C, w0):
    """C restricted to the line {c : w0.c = 0} = {k (w0_2, -w0_1)}, as H(t) (int bitmask), or None."""
    c0 = (w0[1], -w0[0])
    return _sym_to_t([p * c0[0] + q * c0[1] for p, q in C])


def _line_exponent(H, m):
    """A with H(t_j)^2 = t_j^A (j != 0) for H = t^i prod Psi_e^ke with representable e; None if not."""
    A = 0
    while H & 1 == 0:
        H >>= 1
        A += 2
    for e in range(3, 62, 2):
        if H == 1:
            break
        Ae = _A(e, m)
        if Ae is None:
            continue
        while True:
            q, rem = halffrob._cldivmod(H, _psi(e))
            if rem:
                break
            H, A = q, A + Ae
    return A if H == 1 else None


def _score_b(f, m, r, group, ugroups, C, n_names, g):
    """{p: k} for a Theorem-B witness: f^(r) = U * C with U given by ugroups {(w, e): k}, C the core,
    N the orbit units n_names, level g."""
    s = sord(m)
    Ns = 2**s - 1
    Mg = Ns // (2**g - 1)
    r90 = _rule90_powers(m)
    primes = [p for p in _primes_of_s(m) if Mg % p == 0]
    if not ugroups and not n_names:
        return {p: _vp(Mg, p) for p in primes}
    bookU = _Book(m)
    for (w, e), k in ugroups.items():
        bookU.add(w, e, k)
    book = _Book(m)
    for (w, e), k in ugroups.items():
        book.add(w, e, k)
    n_dirs = set()
    for name in n_names:
        kind, v = name
        _, half = _half_orbit(v, group)
        n_dirs |= set(half)
        for w in half:
            if kind == "O":
                book.add_t(w, -1)
            else:
                book.add_psi(w, int(kind[1:]), -1)
    out = {}
    for p in primes:
        k90 = _vp(r90.get(p, 1), p)
        out[p] = book.power(p, k90, _vp(Mg, p))
    if not n_names or all(k == 0 for k in out.values()):
        return out
    # lines where N vanishes: only the O-type directions vanish
    logs = _pow2_log(m)
    for name in n_names:
        kind, v = name
        if kind != "O":
            continue
        _, half = _half_orbit(v, group)
        for w0 in half:
            H = _line_H(C, w0)
            if H is None:
                return {}
            if H == 0:
                continue
            AH = _line_exponent(H, m)
            if AH is None:
                return {}
            c0 = (w0[1], -w0[0])
            total = AH
            seps = list(bookU.sep.values())
            dead = False
            for w, ew in bookU.E.items():
                if ew == 0:
                    continue
                dd = (w[0] * c0[0] + w[1] * c0[1]) % m
                if dd == 0:
                    # t_0 = 0: the unit vanishes on the whole line unless it is a pure Psi product
                    if any(e == 1 and k > 0 for (w2, e), k in ugroups.items() if w2 == w):
                        dead = True
                        break
                    continue
                if dd in logs:
                    total += ew * 2 ** logs[dd]
                else:
                    seps.append(ew)
            if dead:
                continue
            for p in primes:
                k90 = _vp(r90.get(p, 1), p)
                k = out[p]
                if total != 0:
                    k = min(k, k90 + _vp(total, p))
                for b in seps:
                    if b:
                        k = min(k, k90 + _vp(b, p))
                out[p] = k
    return out


def _theorem_b(f, m):
    """The best {p: k} over Theorem-B witnesses, with the witness."""
    s = sord(m)
    Ns = 2**s - 1
    levels = [(g, pow(2, g, m)) for g in range(1, s)
              if s % g == 0 and any((Ns // (2**g - 1)) % p == 0 for p in _primes_of_s(m))]
    if not levels:
        return {}, None
    group = symmetries(f)
    groups, core = unitpower.structure(f)
    ugroups = {}
    for (w, e), (mults, npieces) in groups.items():
        ms = list(mults) + [0] * (npieces - len(mults))
        k = min(ms)
        if any(x != k for x in ms):
            # a partial cyclotomic factor is not a unit: search with f itself as the core
            ugroups, core = {}, f
            break
        ugroups[(w, e)] = k
    natoms = _natoms(group, m)
    perms = {g: (np.arange(m) * n) % m for g, n in levels}
    best = [1, {}, None]

    def consider(r, C, n_names, g, ug):
        sc = _score_b(f, m, r, group, ug, C, n_names, g)
        q = math.prod(p**k for p, k in sc.items())
        if q > best[0]:
            best[:] = [q, sc, dict(r=r, N=list(n_names), g=g, core=C, units=ug)]

    # pure case on f itself
    fm = preduce(f, m)
    for g, n in levels:
        if all(((n * p) % m, (n * q) % m) in fm for p, q in fm):
            consider(1, f, [], g, {})
    core = _center(core)
    if core is None:
        return best[1], best[2]
    maxn = MAX_N if m <= MAX_N_SIZE else MAX_N - 1
    # keep the search tree within a node budget (rules with few symmetries have many orbit units)
    while maxn > 1 and math.comb(len(natoms) + maxn, maxn) > NODE_BUDGET:
        maxn -= 1
    dirs = set()
    for a in natoms:
        dirs |= set(a[2])
    nprobes = 3 if m < 40 else 2
    cands = _probe_dirs(frozenset(dirs), m, nprobes + 6)
    # keep the candidate directions on which the core does not vanish (a zero image tests nothing)
    pdirs = [v for v in cands if all(_Probe(v, m).image(pscale(core, r)).any() for r in (1, 2))][:nprobes]
    if len(pdirs) < nprobes:
        pdirs = list(cands[:nprobes])
    probes = [_Probe(v, m) for v in pdirs]
    atom_f = np.array([[np.fft.rfft(P.image(a[1]).astype(np.float32)) for P in probes] for a in natoms])
    gidx = {g: np.concatenate([perms[g] + k * m for k in range(len(probes))]) for g, _ in levels}

    def image(P_):
        return np.concatenate([P.image(P_) for P in probes]).astype(np.float32)

    def mul(imgs, atoms_i):
        """imgs (k, probes*m) times the atoms atoms_i (k,), exactly, as 0/1 arrays."""
        x = imgs.reshape(len(imgs), len(probes), m)
        prod = np.fft.irfft(np.fft.rfft(x, axis=2) * atom_f[atoms_i], n=m, axis=2)
        return np.fmod(np.abs(np.rint(prod)), 2).astype(np.float32).reshape(len(imgs), -1)

    # invariance under i -> n i is tested by random projections: <x, R> = <x o perm, R>, exact for 0/1 x
    rng = np.random.default_rng(12345)
    R = rng.integers(1, 1 << 12, size=len(probes) * m).astype(np.float32)
    W = np.empty((len(probes) * m, 1 + len(levels)), dtype=np.float32)
    W[:, 0] = R
    for li, (g, _) in enumerate(levels):
        inv = np.empty_like(gidx[g])
        inv[gidx[g]] = np.arange(len(probes) * m)
        W[:, 1 + li] = R[inv]

    Ns = 2**s - 1
    caps = {g: math.prod(p ** _vp(Ns // (2**g - 1), p) for p in _primes_of_s(m)) for g, _ in levels}
    dense_cache = {}

    def dense_of(Cr, combo):
        key = (Cr, combo)
        if key not in dense_cache:
            if not combo:
                dense_cache[key] = _dense(Cr, m)
            else:
                dense_cache[key] = _dense_mul(dense_of(Cr, combo[:-1]), _dense(natoms[combo[-1]][1], m))
        return dense_cache[key]

    def test(imgs, combos, r, Cr, ug):
        H = imgs @ W
        nonzero = np.all(imgs.reshape(len(imgs), len(probes), m).any(axis=2), axis=1)
        for li, (g, n) in enumerate(levels):
            if caps[g] <= best[0]:
                continue  # this level cannot beat the best witness
            ok = (H[:, 0] == H[:, 1 + li]) & nonzero
            for node in np.nonzero(ok)[0]:
                if caps[g] <= best[0]:
                    break
                if not np.array_equal(imgs[node][gidx[g]], imgs[node]):
                    continue
                if _invariant(dense_of(Cr, tuple(combos[node])), n, m):
                    consider(r, Cr, [natoms[i][0] for i in combos[node]], g, ug)

    for r in (1, 2):
        Cr = pscale(core, r)
        if Cr == ONE:
            continue
        ug = {k: r * v for k, v in ugroups.items()}
        base = image(Cr)
        combos, imgs = [()], base[None, :]
        for depth in range(maxn + 1):
            test(imgs, combos, r, Cr, ug)
            if depth == maxn:
                break
            new_combos, parents, atoms_i = [], [], []
            for ni, c in enumerate(combos):
                for i in range(c[-1] if c else 0, len(natoms)):
                    new_combos.append(c + (i,))
                    parents.append(ni)
                    atoms_i.append(i)
            imgs = mul(imgs[parents], np.array(atoms_i))
            combos = new_combos
        # single atoms to a high power (the fifth pilot's certificates f M^E)
        imgs = np.repeat(base[None, :], len(natoms), axis=0)
        ids = np.arange(len(natoms))
        for e in range(1, (MAX_POWER if m <= MAX_POWER_SIZE else MAX_POWER // 3) + 1):
            imgs = mul(imgs, ids)
            if e > maxn:
                test(imgs, [(i,) * e for i in ids], r, Cr, ug)
    return best[1], best[2]


